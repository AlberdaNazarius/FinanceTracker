create or replace function public.handle_new_user()
  returns trigger
  language plpgsql
  security definer
  AS $function$
begin
  insert into public.user (id, username)
  values (
    new.id,
    new.raw_user_meta_data->>'username'
  );

  return new;
end;
$function$;

