create view "public"."budget_summary" with (security_invoker=on) AS  SELECT b.id AS budget_id,
    b.user_id,
    c.name AS category,
    c.color AS category_color,
    c.icon AS category_icon,
    b.amount AS budget,
    COALESCE(sum(t.amount), (0)::real) AS spent,
    ((b.amount)::double precision - COALESCE(sum(t.amount), (0)::real)) AS remaining,
    round((((COALESCE(sum(t.amount), (0)::real) / (NULLIF(b.amount, (0)::numeric))::double precision) * (100)::double precision))::numeric, 2) AS used_percent
   FROM ((public.budget b
     JOIN public.category c ON ((c.id = b.category_id)))
     LEFT JOIN public.transaction t ON (((t.category_id = b.category_id) AND (t.transaction_date >= b.period_start) AND (t.transaction_date < (b.period_end + '1 day'::interval)))))
  GROUP BY b.id, c.name, c.color, c.icon;

create view "public"."user_balance" with (security_invoker=on) AS  SELECT user_id,
    COALESCE(sum(
        CASE
            WHEN (type = 'income'::text) THEN amount
            ELSE (- amount)
        END), (0)::real) AS balance
   FROM public.transaction
  GROUP BY user_id;

